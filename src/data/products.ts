export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function getProductsByCategory(category: string): Product[] {
  return PRODUCTS.filter((p) => p.category === category);
}

export function getProductsByOccasion(occasion: string): Product[] {
  return PRODUCTS.filter((p) => p.occasionTags.includes(occasion as any));
}

export function getProductsByPriceRange(range: string): Product[] {
  return PRODUCTS.filter((p) => p.priceRange === range);
}

export function getTrendingProducts(): Product[] {
  return PRODUCTS.filter((p) => p.isTrending).sort((a, b) => b.popularityScore - a.popularityScore);
}

export function getFeaturedProducts(): Product[] {
  return PRODUCTS.filter((p) => p.isFeatured).sort((a, b) => b.popularityScore - a.popularityScore);
}
